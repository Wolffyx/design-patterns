#!/usr/bin/env node
/**
 * build-antisignals.js
 *
 * Extracts the "Don't use when" section from each references/<pattern>.md
 * and writes references/_antisignals.json for the preamble validator (I2).
 *
 * Run manually whenever a reference file changes:
 *   node ~/.claude/skills/design-patterns/build-antisignals.js
 *
 * Output shape:
 *   {
 *     "Singleton": [
 *       "A store slice or DI container would do",
 *       "The \"singleton\" is just stateless utility functions",
 *       ...
 *     ],
 *     ...
 *   }
 *
 * Validator grep-matches preamble reason (case-insensitive substring) against
 * the cited pattern's phrases; match → non-blocking stderr warn.
 */

const fs = require('fs');
const path = require('path');

const REF_DIR = path.join(__dirname, 'references');
const OUT_PATH = path.join(REF_DIR, '_antisignals.json');

function extractFrontmatterName(text) {
    const m = text.match(/^---\s*\nname:\s*([^\n]+?)\s*\n/);
    return m ? m[1].trim() : null;
}

function extractDontUseSection(text) {
    // find `## Don't use when` heading to next `##` heading
    const re = /##\s+Don'?t use when\s*\n([\s\S]*?)(?=\n##\s+|\n---\s*\n|$)/i;
    const m = text.match(re);
    return m ? m[1].trim() : '';
}

function extractBullets(section) {
    const out = [];
    const lines = section.split('\n');
    for (const line of lines) {
        const m = line.match(/^[-*]\s+(.+?)\s*$/);
        if (!m) continue;
        // strip trailing backtick-markers, arrows to commentary
        let phrase = m[1];
        // split on ` \u2192 ` (→) — take the LEFT side as the antisignal phrase
        const arrowIdx = phrase.indexOf('\u2192');
        if (arrowIdx > 0) phrase = phrase.slice(0, arrowIdx).trim();
        // strip surrounding markdown emphasis
        phrase = phrase.replace(/[`*_]/g, '').trim();
        if (phrase.length >= 4) out.push(phrase);
    }
    return out;
}

function main() {
    const files = fs.readdirSync(REF_DIR)
        .filter(f => f.endsWith('.md') && !f.startsWith('_'));
    const out = {};
    let total = 0;
    for (const file of files) {
        const full = path.join(REF_DIR, file);
        const text = fs.readFileSync(full, 'utf8');
        const name = extractFrontmatterName(text);
        if (!name) continue;
        const section = extractDontUseSection(text);
        if (!section) continue;
        const bullets = extractBullets(section);
        if (bullets.length === 0) continue;
        out[name] = bullets;
        total += bullets.length;
    }
    const header = '// generated by build-antisignals.js — do not edit by hand\n';
    // write as JSON; header comment is for humans grepping the file, not parsed
    fs.writeFileSync(OUT_PATH, JSON.stringify(out, null, 2) + '\n', 'utf8');
    process.stdout.write('Wrote ' + OUT_PATH + '\n');
    process.stdout.write('Patterns: ' + Object.keys(out).length + ', phrases: ' + total + '\n');
}

main();
